"use client";

import React, { useEffect, useState } from "react";
import { Users2, Mail, Phone, Building, Sparkles } from "lucide-react";
import StatusBadge from "@/components/ui/StatusBadge";
import { leadsApi } from "@/lib/api/leads";

export default function AdminLeadsPage() {
  const [leads, setLeads] = useState([]);

  useEffect(() => {
    async function load() {
      const data = await leadsApi.getLeads();
      setLeads(data);
    }
    load();
  }, []);

  return (
    <div className="space-y-8 animate-fade-in pb-12">
      <div>
        <h1 className="text-2xl sm:text-3xl font-extrabold tracking-tight text-slate-900">
          Global Generated Leads
        </h1>
        <p className="text-xs sm:text-sm text-slate-500 mt-1">
          High-commercial-intent leads generated by all customer assistants across all tenants.
        </p>
      </div>

      <div className="bg-white rounded-2xl border border-slate-200/80 overflow-hidden shadow-xs">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead className="bg-slate-50/80 text-slate-500 font-semibold text-[11px] uppercase tracking-wider border-b border-slate-200/80">
              <tr>
                <th className="p-4">Lead Contact</th>
                <th className="p-4">Customer Company</th>
                <th className="p-4">Assisting Bot</th>
                <th className="p-4">Commercial Score</th>
                <th className="p-4">Channel</th>
                <th className="p-4">Pipeline Status</th>
                <th className="p-4 text-right">Created</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {leads.length === 0 ? (
                <tr>
                  <td colSpan={7} className="p-8 text-center text-slate-400">
                    No leads generated yet. Leads captured by your chatbots will appear here in real time.
                  </td>
                </tr>
              ) : (
                leads.map((l) => (
                  <tr key={l.id} className="hover:bg-slate-50/60 transition-colors">
                    <td className="p-4">
                      <p className="font-bold text-slate-900">{l.name || "Website Prospect"}</p>
                      <p className="text-[11px] text-slate-500">{l.phone || l.email || "No contact shared yet"}</p>
                    </td>
                    <td className="p-4 text-slate-700 font-medium">{l.company || "Direct Inbound"}</td>
                    <td className="p-4 text-slate-600">{l.bot || l.botName || "aa"}</td>
                    <td className="p-4">
                      <StatusBadge status={l.score || "Medium"} size="sm" />
                    </td>
                    <td className="p-4 text-slate-500">{l.source || "Web Chatbot"}</td>
                    <td className="p-4">
                      <StatusBadge status={l.status || "New"} size="sm" />
                    </td>
                    <td className="p-4 text-right text-slate-400">
                      {l.created || (l.createdAt ? l.createdAt.split("T")[0] : "Just now")}
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
}
